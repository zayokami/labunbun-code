#!/usr/bin/env bun
/**
 * Turn the repository's built-in skills into a module the binary can carry.
 *
 * `.labunbun/skills` is a directory of Markdown, and a compiled binary has no
 * directory to read it from: the release artifacts put one executable in
 * `usr/bin` (or one `.exe` in Program Files) and nothing beside it. Bun's
 * `with { type: "file" }` import is the supported way to put a file inside the
 * executable, and once it is there `readFileSync` on the imported path works the
 * same in `bun run dev` and in `bun build --compile` (verified against Bun
 * 1.4.4; the path is the real one in dev and `B:/~BUN/root/...` in the binary).
 *
 * The imports have to be static, so this script writes them down. The output is
 * checked in: a fresh clone can typecheck without running anything, and
 * `bundled-skills.test.ts` compares it against a fresh render, so a skill added
 * to the tree without regenerating is a red test rather than a binary that
 * ships yesterday's list.
 *
 * Usage:
 *   bun run scripts/bundle-skills.ts           write the module
 *   bun run scripts/bundle-skills.ts --check   fail if it is stale
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const REPO = resolve(import.meta.dir, "..");
const OUTPUT = join(REPO, "packages", "coding-agent", "src", "bundled-skills.generated.ts");

/** Every file under the skills root, repository-relative and slash-separated. */
function skillFiles(root: string): string[] {
	const out: string[] = [];
	const walk = (dir: string): void => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else if (entry.isFile()) out.push(relative(root, full).split("\\").join("/"));
		}
	};
	walk(root);
	return out.sort();
}

/**
 * The module text. Import identifiers are positional (`f0`, `f1`, …) because the
 * skill names contain hyphens and the only thing that matters is that each file
 * is imported once and paired with its path.
 */
export function renderBundledSkillsModule(repo = REPO): string {
	const root = join(repo, ".labunbun", "skills");
	const files = skillFiles(root);
	const imports = files.map((file, index) => {
		const specifier = join("..", "..", "..", ".labunbun", "skills", file).split("\\").join("/");
		const oneLine = `import f${index} from ${JSON.stringify(specifier)} with { type: "file" };`;
		// Match the formatter the repository runs: biome breaks the attributes
		// onto their own lines past the print width. Emitting the unbroken line
		// would leave the checked-in module permanently "unformatted", and
		// `bun run skills:bundle` would keep rewriting it into a lint failure.
		if (oneLine.length <= 120) return oneLine;
		return `import f${index} from ${JSON.stringify(specifier)} with {\n\ttype: "file",\n};`;
	});
	const entries = files.map((file, index) => `\t[${JSON.stringify(file)}, f${index}],`);
	return [
		"// Generated by scripts/bundle-skills.ts from .labunbun/skills. Do not edit.",
		"// Run `bun run skills:bundle` after adding, removing or editing a skill.",
		...imports,
		'import type { BundledSkillFile } from "./bundled-skills.ts";',
		"",
		"/** Every built-in skill file, keyed by its path under the skills root. */",
		"export const BUNDLED_SKILL_FILES: ReadonlyArray<BundledSkillFile> = [",
		...entries,
		"];",
		"",
	].join("\n");
}

export function writeBundledSkillsModule(repo = REPO): void {
	const output = join(repo, "packages", "coding-agent", "src", "bundled-skills.generated.ts");
	mkdirSync(dirname(output), { recursive: true });
	writeFileSync(output, renderBundledSkillsModule(repo));
}

if (import.meta.main) {
	const check = process.argv.includes("--check");
	const expected = renderBundledSkillsModule(REPO);
	if (check) {
		if (!existsSync(OUTPUT) || readFileSync(OUTPUT, "utf8") !== expected) {
			console.error("bundled-skills.generated.ts is stale; run `bun run skills:bundle`.");
			process.exit(1);
		}
		console.log("bundled skills are up to date");
	} else {
		writeFileSync(OUTPUT, expected);
		console.log(`wrote ${relative(REPO, OUTPUT)}`);
	}
}
